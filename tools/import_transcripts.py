# -*- coding: utf-8 -*-
"""Import data that is already dialogue, skipping steps 01 through 05.

Steps 01-04 exist to *build* transcripts out of prose. If what you have is
already in transcript form — chat logs, exported roleplay sessions, a ShareGPT
dataset — running them through segmentation and conversion is expensive and
lossy. This tool writes the same files those steps would have produced, so the
rest of the pipeline works unchanged:

    python tools/import_transcripts.py logs/*.txt
    python 06_format.py          # -> ShareGPT dataset
    python 07_augment.py         # -> format variation across axes
    python 08_assemble.py        # -> + optional diluent

Two input formats, detected automatically:

  ShareGPT JSONL   one session per line, `conversations` or `messages`, with any
                   of the usual role names. System messages are used to guess the
                   character name and then dropped.
  Plain-text log   `Name: line` per turn. Sessions are separated by a break line
                   (`* * *`, `---`) or, if the file has none, by two or more blank
                   lines.

What it writes into the workdir:

  rp_clean.jsonl   the transcripts, in the schema step 04 produces
  scenes.jsonl     one "scene" per transcript, holding the same text

The second file is not decoration. Step 07 needs a corpus to measure word rarity
against, and it uses each transcript's own text as the style reference for a row
that has no source prose. Building scenes.jsonl from the transcripts themselves
is what makes that correct here: the imported dialogue *is* the style reference.

Common options:

    --char NAME        force the played character instead of inferring it
    --user NAME        force the interlocutor's name
    --keep-names       keep `Name:` prefixes in the turn text (default: strip)
    --min-turns N      drop sessions shorter than this (default 2)
    --max-chars N      trim long sessions on turn borders (default 14000)
    --safety-filter    apply the content filter from pipeline/safety.py
    --force            overwrite an existing rp_clean.jsonl
    --dry-run          report what would be imported, write nothing
"""
import argparse
import os
import re
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from pipeline.axes import clean_macros  # noqa: E402
from pipeline.config import load_config, work_path  # noqa: E402
from pipeline.files import read_dataset, read_text, write_jsonl  # noqa: E402
from pipeline.lang import load_pack  # noqa: E402
from pipeline.safety import flag_session  # noqa: E402
from pipeline.sharegpt import merge_turns, normalize_entry  # noqa: E402
from pipeline.textstats import percentile  # noqa: E402

# A line of repeated separator characters, the same convention step 01 uses.
SESSION_BREAK = re.compile(r"^\s*([*#~—\-–_=]\s*){3,}\s*$")
# `Name: text`. The name is bounded in length so a sentence containing a colon
# is not mistaken for a speaker label.
SPEAKER_LINE = re.compile(r"^\s{0,3}([^\n:]{1,40}?)\s*:\s+(.*)$")
# "You are Ivan", "Ты — Иван", "Character: Ivan" and similar openings.
CARD_NAME = re.compile(
    r"(?:you are|you're|act as|roleplay as|character\s*[:=]|ты\s*[—-]|отыгрывай)\s+"
    r"([^\s,.;:]{2,30})", re.I)


# ---------------------------------------------------------------------------
# ShareGPT input
# ---------------------------------------------------------------------------

def guess_char_name(conversation, fallback):
    """Pull the character name out of a system card, or fall back."""
    for message in conversation:
        if message["from"] != "system":
            continue
        match = CARD_NAME.search(message["value"])
        if match:
            name = match.group(1).strip(" \"'*«»„“”")
            if len(name) >= 2:
                return name
    return fallback


def from_sharegpt(path, char_override, user_override, pack):
    """Read a ShareGPT file into (char, user, turns) tuples."""
    raw = read_dataset(path)
    sessions = []
    for entry in raw:
        conversation = normalize_entry(entry)
        if not conversation:
            continue
        char = char_override or guess_char_name(conversation, pack.fallback_char)
        user = user_override or pack.fallback_user
        turns = []
        for message in conversation:
            if message["from"] == "system":
                # The card is regenerated by step 06 or 07 from the language
                # pack, so carrying the old one through would produce two.
                continue
            text = clean_macros(message["value"], char, user)
            if not text:
                continue
            turns.append({"role": "user" if message["from"] == "human" else "char",
                          "text": text})
        if turns:
            sessions.append((char, user, turns))
    return sessions, len(raw)


# ---------------------------------------------------------------------------
# Plain-text log input
# ---------------------------------------------------------------------------

def split_sessions(text):
    """Cut a log file into sessions.

    A break line wins if the file has any. Otherwise two or more blank lines are
    treated as the separator, which is how most exported logs look. A file with
    neither becomes a single session, and the caller warns about that.
    """
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = text.split("\n")
    if any(SESSION_BREAK.match(line) for line in lines):
        chunks, current = [], []
        for line in lines:
            if SESSION_BREAK.match(line):
                if any(l.strip() for l in current):
                    chunks.append("\n".join(current))
                current = []
            else:
                current.append(line)
        if any(l.strip() for l in current):
            chunks.append("\n".join(current))
        return chunks, "break lines"
    chunks = [c for c in re.split(r"\n\s*\n\s*\n+", text) if c.strip()]
    if len(chunks) > 1:
        return chunks, "blank-line groups"
    return [text], "none found"


def parse_log_session(block, keep_names):
    """Parse one session into [(speaker, text)], joining wrapped lines."""
    turns = []
    for line in block.split("\n"):
        if not line.strip():
            continue
        match = SPEAKER_LINE.match(line)
        if match:
            speaker, text = match.group(1).strip(), match.group(2).strip()
            if keep_names:
                text = f"{speaker}: {text}"
            turns.append([speaker, text])
        elif turns:
            # A continuation line of the previous turn.
            turns[-1][1] += "\n" + line.strip()
        # A line before any speaker label is a header or a stray; skipped.
    return [(speaker, text) for speaker, text in turns if text.strip()]


def from_log(path, char_override, user_override, keep_names, encodings, pack):
    """Read a `Name: line` log file into (char, user, turns) tuples."""
    text = read_text(path, encodings, verbose=False)
    blocks, how = split_sessions(text)
    print(f"  {path}: {len(blocks)} sessions (split by {how})")
    if how == "none found" and len(text) > 20000:
        print(f"  [!] no session separator found in a {len(text)}-character file. "
              f"Everything becomes one session. Insert '* * *' lines between "
              f"sessions, or use --session-break.")

    sessions = []
    for block in blocks:
        parsed = parse_log_session(block, keep_names)
        if not parsed:
            continue
        counts = Counter(speaker for speaker, _text in parsed)
        ordered = [name for name, _n in counts.most_common()]
        char = char_override or ordered[0]
        user = user_override or next((n for n in ordered if n != char), pack.fallback_user)

        # Everyone who is neither char nor user becomes part of the world: their
        # lines are folded into the preceding character turn as narration. That
        # is the same rule step 03 applies to crowd scenes.
        turns = []
        for speaker, line_text in parsed:
            if speaker == user:
                turns.append({"role": "user", "text": line_text})
            elif speaker == char:
                turns.append({"role": "char", "text": line_text})
            elif turns and turns[-1]["role"] == "char":
                turns[-1]["text"] += "\n\n" + line_text
            else:
                turns.append({"role": "char", "text": line_text})
        if turns:
            sessions.append((char, user, turns))
    return sessions, len(blocks)


# ---------------------------------------------------------------------------
# Shared post-processing
# ---------------------------------------------------------------------------

def detect_format(path):
    if path.endswith((".jsonl", ".json", ".parquet")):
        return "sharegpt"
    return "log"


def trim_turns(turns, max_chars):
    """Cut a session to a character budget on turn borders."""
    kept, used = [], 0
    for turn in turns:
        if used + len(turn["text"]) > max_chars and kept:
            break
        kept.append(turn)
        used += len(turn["text"])
    return kept


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("inputs", nargs="+", help="log .txt or ShareGPT .jsonl/.parquet files")
    parser.add_argument("--config", default="config.yaml")
    parser.add_argument("--format", choices=["auto", "sharegpt", "log"], default="auto")
    parser.add_argument("--char", default=None, help="force the played character's name")
    parser.add_argument("--user", default=None, help="force the interlocutor's name")
    parser.add_argument("--keep-names", action="store_true",
                        help="keep `Name:` prefixes in the text (default: strip)")
    parser.add_argument("--min-turns", type=int, default=2)
    parser.add_argument("--max-chars", type=int, default=14000)
    parser.add_argument("--session-break", default=None,
                        help="regex marking a session separator in a log file")
    parser.add_argument("--safety-filter", action="store_true",
                        help="apply the content filter from pipeline/safety.py")
    parser.add_argument("--force", action="store_true", help="overwrite existing output")
    parser.add_argument("--dry-run", action="store_true", help="report only, write nothing")
    args = parser.parse_args()

    cfg = load_config(args.config)
    pack = load_pack(cfg["lang"])

    if args.session_break:
        global SESSION_BREAK
        SESSION_BREAK = re.compile(args.session_break, re.M)

    out_transcripts = work_path(cfg, "rp_clean.jsonl")
    out_scenes = work_path(cfg, "scenes.jsonl")
    for path in (out_transcripts, out_scenes):
        if os.path.exists(path) and not args.force and not args.dry_run:
            sys.exit(
                f"\n{path} already exists.\n"
                f"This tool replaces it wholesale rather than resuming, so it will not "
                f"overwrite by accident.\nUse --force, or point workdir at a fresh "
                f"folder in the config.\n")

    collected, total_read = [], 0
    for path in args.inputs:
        if not os.path.exists(path):
            print(f"  [warn] {path}: not found, skipped", file=sys.stderr)
            continue
        kind = args.format if args.format != "auto" else detect_format(path)
        if kind == "sharegpt":
            sessions, count = from_sharegpt(path, args.char, args.user, pack)
            print(f"  {path}: {len(sessions)} usable sessions out of {count} (ShareGPT)")
        else:
            sessions, count = from_log(path, args.char, args.user, args.keep_names,
                                       cfg["input"]["encodings"], pack)
        collected += sessions
        total_read += count

    assert collected, "nothing could be imported — check the input format and --format"

    # Filter, trim, and drop sessions that cannot serve as a training target.
    transcripts, scenes = [], []
    dropped = Counter()
    for char, user, turns in collected:
        turns = merge_turns([{"role": t["role"], "text": t["text"]} for t in turns])
        turns = trim_turns(turns, args.max_chars)
        while turns and turns[-1]["role"] == "user":
            turns.pop()
        if len(turns) < args.min_turns:
            dropped["too few turns"] += 1
            continue
        if not any(t["role"] == "char" for t in turns):
            dropped["no character turn"] += 1
            continue
        if args.safety_filter:
            as_messages = [{"from": "gpt" if t["role"] == "char" else "human",
                            "value": t["text"]} for t in turns]
            reason = flag_session(as_messages)
            if reason:
                dropped["content filter"] += 1
                continue

        text = "\n\n".join(t["text"] for t in turns)
        scene_id = len(scenes)
        scenes.append({"id": scene_id, "chapter": "", "text": text, "chars": len(text)})
        transcripts.append({
            "id": len(transcripts),
            # Pointing at the scene built from this very transcript is what makes
            # step 07 use the imported dialogue as its own style reference.
            "source_id": scene_id,
            "char": char, "user": user, "turns": turns,
            "imported": True,
        })

    print(f"\nImported: {len(transcripts)} transcripts from {total_read} input sessions")
    for reason, count in dropped.most_common():
        print(f"  dropped {count:>5}  {reason}")

    lengths = sorted(scene["chars"] for scene in scenes)
    if lengths:
        print(f"Session length in characters: min {lengths[0]}, "
              f"median {percentile(lengths, .5)}, max {lengths[-1]}")
    characters = Counter(t["char"] for t in transcripts)
    print(f"Characters: {', '.join(f'{n} ({c})' for n, c in characters.most_common(6))}")
    if len(characters) == 1 and not args.char:
        print("  [!] every session got the same character name. That is correct for a "
              "log with one recurring character, and wrong for a ShareGPT source whose "
              "system cards could not be read — check one transcript, and pass --char "
              "if the name is a fallback rather than a real one.")

    if args.dry_run:
        print("\n[--dry-run] Nothing written.")
        return

    write_jsonl(out_scenes, scenes)
    write_jsonl(out_transcripts, transcripts)
    print(f"\nWritten:\n  {out_transcripts}\n  {out_scenes}")
    print("\nNext: python 06_format.py, then 07_augment.py, then 08_assemble.py.")
    print("Do NOT run steps 01-05 on this workdir — they would overwrite these files.")
    if cfg["synth"]["enabled"]:
        print("\nNote: synth.enabled is true, but step 05 needs scenes_attr.jsonl from "
              "step 02, which does not exist here. Either set synth.enabled to false, "
              "or generate synthetic rows in a separate workdir built from prose.")


if __name__ == "__main__":
    main()
